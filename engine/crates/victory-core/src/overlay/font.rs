/// The rows of the glyph for `c` (`?` for anything unprintable): bit 4 is
/// the leftmost pixel.
pub fn glyph(c: char) -> [u8; 8] {
    let index = match c as u32 {
        n @ 32..=126 => (n - FIRST) as usize,
        _ => ('?' as u32 - FIRST) as usize,
    };
    let mut rows = [0u8; 8];
    for (row, text) in GLYPHS[index].split('/').enumerate().take(8) {
        for (col, ch) in text.bytes().enumerate().take(5) {
            if ch == b'#' {
                rows[row] |= 0x10 >> col;
            }
        }
    }
    rows
}

/// The atlas texels, `ATLAS_W` by `ATLAS_H`, one byte each.
pub fn atlas() -> Vec<u8> {
    let mut texels = vec![0u8; (ATLAS_W * ATLAS_H) as usize];
    for n in FIRST..=126 {
        let (cx, cy) = cell_of(char::from_u32(n).unwrap_or('?'));
        for (y, bits) in glyph(char::from_u32(n).unwrap_or('?')).iter().enumerate() {
            for x in 0..5u32 {
                if bits & (0x10 >> x) != 0 {
                    texels[((cy + y as u32) * ATLAS_W + cx + x) as usize] = 255;
                }
            }
        }
    }
    let (sx, sy) = solid_cell();
    for y in 0..CELL {
        for x in 0..CELL {
            texels[((sy + y) * ATLAS_W + sx + x) as usize] = 255;
        }
    }
    texels
}

/// Where a glyph is in the atlas, in texels: x, y of its cell.
pub fn cell_of(c: char) -> (u32, u32) {
    let n = match c as u32 {
        n @ 32..=126 => n - FIRST,
        _ => '?' as u32 - FIRST,
    };
    ((n % 16) * CELL, (n / 16) * CELL)
}

/// The cell of the solid block.
pub fn solid_cell() -> (u32, u32) {
    ((SOLID_CELL % 16) * CELL, (SOLID_CELL / 16) * CELL)
}

/// The width of `text` at `scale` pixels per font pixel.
pub fn text_width(text: &str, scale: f32) -> f32 {
    text.chars().count() as f32 * ADVANCE as f32 * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_eight_rows_of_five() {
        for (i, g) in GLYPHS.iter().enumerate() {
            let rows: Vec<&str> = g.split('/').collect();
            assert_eq!(
                rows.len(),
                8,
                "glyph {:?}",
                char::from_u32(i as u32 + FIRST)
            );
            for r in rows {
                assert_eq!(
                    r.len(),
                    5,
                    "glyph {:?} row {r}",
                    char::from_u32(i as u32 + FIRST)
                );
                assert!(r.bytes().all(|b| b == b'#' || b == b'.'));
            }
        }
    }

    #[test]
    fn the_atlas_has_a_solid_cell_and_the_letters_differ() {
        let a = atlas();
        assert_eq!(a.len(), (ATLAS_W * ATLAS_H) as usize);
        let (sx, sy) = solid_cell();
        for y in 0..CELL {
            for x in 0..CELL {
                assert_eq!(a[((sy + y) * ATLAS_W + sx + x) as usize], 255);
            }
        }
        // Space is empty; a letter has set texels in its 5 columns only.
        let (cx, cy) = cell_of('H');
        let set: Vec<(u32, u32)> = (0..CELL)
            .flat_map(|y| (0..CELL).map(move |x| (x, y)))
            .filter(|&(x, y)| a[((cy + y) * ATLAS_W + cx + x) as usize] != 0)
            .collect();
        assert!(!set.is_empty() && set.iter().all(|&(x, _)| x < 5));
        let (spx, spy) = cell_of(' ');
        assert!(
            (0..CELL).all(|y| (0..CELL).all(|x| a[((spy + y) * ATLAS_W + spx + x) as usize] == 0))
        );
        assert_ne!(glyph('b'), glyph('d'));
        assert_eq!(glyph('\u{1}'), glyph('?'));
    }
}
